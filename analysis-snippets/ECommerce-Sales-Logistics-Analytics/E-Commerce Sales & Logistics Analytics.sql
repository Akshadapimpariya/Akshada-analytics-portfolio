-- Monthly Revenue Trend (2024 vs 2025)
WITH monthly_sales AS (
    SELECT 
        DATE_TRUNC('month', o.order_date) AS month,
        SUM(o.quantity * p.price) AS revenue
    FROM orders o
    JOIN products p ON o.product_id = p.product_id
    WHERE o.status = 'Completed'
    GROUP BY month
)
SELECT 
    month,
    revenue,
    LAG(revenue) OVER (ORDER BY month) AS prev_revenue,
    round((revenue - LAG(revenue) OVER (ORDER BY month)) * 100.0 
        / NULLIF(LAG(revenue) OVER (ORDER BY month), 0),2) AS mom_growth_pct
FROM monthly_sales;


-- Compare the performance of each month in 2024 against the same month in 2025 to see if the business is expanding.
with monthlysales as(
     select
	 extract(month from order_date) as month_num,
	 extract(year from order_date) as order_year,
	 sum(o.quantity * p.price) as monthly_revenue
	 from orders o 
	 join products p on p.product_id = o.product_id
	 WHERE o.status = 'Completed'
	 group by 1,2
)
select
s24.month_num,
round(s24.monthly_revenue,2) as revenue_24,
round(s25.monthly_revenue,2) as revenue_25,
round((s25.monthly_revenue - s24.monthly_revenue/s24.monthly_revenue)*100,2) yoy_growth_pct
from monthlysales s24
join monthlysales s25 on s24.month_num = s25.month_num
where s24.order_year = 2024 and s25.order_year = 2025
order by s24.month_num;

-- Identify if 80% of the total revenue is generated by a small percentage (the top 20%) of your products.
with productsales as(
     select
	 p.product_id,
	 sum(o.quantity*p.price) as total_Revenue
	 from products p 
	 join orders o on o.product_id = p.product_id
	 where o.status = 'Completed'
	 group by 1
),
runningpercentage as(
   select
   product_id,
   total_revenue,
   sum(total_revenue) over(order by total_Revenue desc) /
   sum(total_revenue) over() cumulative_pct
   from productsales
)

-- Smooth out those holiday "spikes" in Nov/Dec to see the real sales trend.
select
 order_month,
 total_revenue,
 avg(total_revenue) over(order by order_month rows between 2 preceding and current row) as rolling_3pt_avg
 from(
 select
 date_trunc('month',order_date) as order_month,
 sum(quantity * price) as total_revenue
 from orders 
 join products on orders.product_id = products.product_id
 group by 1) sub;

-- Find out how much money we are losing because people cancel or return items.
SELECT
status,
sum(o.quantity * p.price) as revenue_loss
from orders o
join products p on p.product_id = o.product_id
where status != 'Completed'
group by 1;

-- Top 5 Best-Selling Categories
