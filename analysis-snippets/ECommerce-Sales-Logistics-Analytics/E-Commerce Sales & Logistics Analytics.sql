-- Ranking Products by Sales in Each Category
with product_rank as (
     select
	 category,
	 product_name,
	 sum(quantity) as total_sales,
	 dense_rank() over(partition by category order by sum(quantity) desc) as rn
	 from orders 
	 join products on products.product_id = orders.product_id
	 group by 1,2
)
select * from product_rank
where rn =1;

-- See how total profit builds up day by day throughout the year.
with dailyprofit as(
     select
	 order_Date,
	 sum(quantity*(price-cost)) as profit
	 from orders join products 
	 on products.product_id = orders.product_id
	 where status = 'Completed'
	 group by 1
)
SELECT
order_date,
profit,
sum(profit) over(partition by order_Date) as running_total_profit
from dailyprofit;


-- Comparing Individual Orders to the Average
WITH OrderTotals AS (
    SELECT 
        order_id,
        SUM(quantity * price) AS total_order_value
    FROM orders o
    JOIN products p ON o.product_id = p.product_id
    GROUP BY 1
)
SELECT 
    order_id,
    total_order_value,
    AVG(total_order_value) OVER () AS global_avg_order
FROM OrderTotals
WHERE total_order_value > (SELECT AVG(quantity * price) FROM orders o JOIN products p 
                           ON o.product_id = p.product_id) * 2;

-- See if today's sales are better than yesterday's using a Window Function.
with daily_sales as(
      select 
	  order_date,
	  sum(quantity * price) as daily_revenue
	  from orders join products on products.product_id = orders.product_id
	  group by 1
)
SELECT
order_Date,
daily_revenue,
lag(daily_revenue) over(order by order_date) as yesterday_revenue,
daily_revenue - lag(daily_revenue) over(order by order_date) as daily_diff
from daily_sales;

-- Identify customers who placed an order in 2024 but have zero orders in 2025. This helps the marketing team target "lost" customers.
SELECT
user_id,user_name
from users
where user_id in (
     select user_id from orders where extract(year from order_date) = 2024
)
and user_id not in(
    select user_id from orders where extract(year from order_date) = 2025
);

-- Find out what percentage of your customers are "Loyal" (ordered more than 3 times) compared to the average.
with loyalcustomers as(
     select
	 user_id,
	 count(order_id) as order_count
	 from orders
	 group by user_id
)
select
order_count,
count(user_id) as total_customers,
sum(count(user_id)) over() as global_total_user,
round(count(user_id)*100.0/sum(count(user_id)) over(),2) as percent
from loyalcustomers
group by order_count
order by order_count desc;

-- Find orders that took longer than the average shipping time of their specific ship_mode.
with shiptime as(
     select
	 o.order_id,
	 s.ship_mode,
	 (s.ship_date - o.order_date) as days_To_ship
	 from orders o
	 join shipping s on o.order_id = s.order_id
)

select * from shiptime st
where days_To_ship > (
    select avg(days_To_ship)
	from shiptime stt
	where st.ship_mode = stt.ship_mode
)
limit 10;

-- Find products that have never been ordered. These are "dead stock" taking up space in your database.
SELECT product_id, product_name, category
FROM products
WHERE product_id NOT IN (
    SELECT DISTINCT product_id FROM orders
);
