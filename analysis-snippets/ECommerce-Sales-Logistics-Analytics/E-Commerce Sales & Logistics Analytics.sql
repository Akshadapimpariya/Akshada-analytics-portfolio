CREATE TABLE users (
    user_id serial,
    user_name VARCHAR(100),
    country VARCHAR(100),
    signup_date DATE,
    is_premium INT
);

CREATE TABLE products (
    product_id INT PRIMARY KEY,
    product_name VARCHAR(255),
    category VARCHAR(100),
    price DECIMAL(10,2),
    cost DECIMAL(10,2)
);

CREATE TABLE orders (
    order_id INT PRIMARY KEY,
    user_id INT,
    product_id INT,
    order_date DATE,
    quantity INT,
    status VARCHAR(50)
);

CREATE TABLE shipping (
    shipping_id INT PRIMARY KEY,
    order_id INT,
    ship_mode VARCHAR(50),
    shipping_fee DECIMAL(10,2),
    ship_date DATE
);

